/// Returns the stable representative of `cp`'s simple-case-fold class.
/// Code points absent from the Unicode table are returned unchanged.
pub fn canonical(cp: u21) u21 {
    var low: usize = 0;
    var high: usize = firsts.len;
    while (low < high) {
        const mid = low + (high - low) / 2;
        if (cp < firsts[mid]) {
            high = mid;
        } else if (cp > lasts[mid]) {
            low = mid + 1;
        } else {
            const distance = cp - firsts[mid];
            const stride: u2 = if (stride_twos[mid / 8] & (@as(u8, 1) << @intCast(mid % 8)) != 0) 2 else 1;
            if (distance % stride == 0) {
                return @intCast(@as(i32, cp) + deltas[mid]);
            }
            return cp;
        }
    }
    return cp;
}

const testing = @import("std").testing;

fn expectClass(comptime points: []const u21) !void {
    const expected = canonical(points[0]);
    for (points) |point| try testing.expectEqual(expected, canonical(point));
}

test "representative case-fold classes" {
    try expectClass(&.{ 'A', 'a' });
    try expectClass(&.{ 'K', 'k', 'K' });
    try expectClass(&.{ 'S', 's', 'ſ' });
    try expectClass(&.{ 'µ', 'Μ', 'μ' });
    try expectClass(&.{ 'ß', 'ẞ' });
    try expectClass(&.{ 'Ա', 'ա' });
}

test "unrelated code points stay distinct" {
    try testing.expectEqual(@as(u21, '0'), canonical('0'));
    try testing.expectEqual(@as(u21, 0x1F600), canonical(0x1F600));
    try testing.expect(canonical('a') != canonical('b'));
    try testing.expect(canonical('µ') != canonical('m'));
}
